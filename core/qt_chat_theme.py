def text(value, size=11, color='#e8e3ef', bold=False):
    w = QLabel(value)
    w.setFont(QFont('Segoe UI', size, QFont.Weight.DemiBold if bold else QFont.Weight.Normal))
    w.setStyleSheet(f'color:{color};background:transparent;border:0;')
    return w

def icon(kind, color='#a59ab6'):
    pix = QPixmap(48, 48)
    pix.fill(Qt.GlobalColor.transparent)
    p = QPainter(pix)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    p.scale(2, 2)
    p.setPen(QPen(QColor(color), 1.5, Qt.PenStyle.SolidLine, Qt.PenCapStyle.RoundCap))
    if kind == 'plus':
        p.drawLine(12, 5, 12, 19)
        p.drawLine(5, 12, 19, 12)
    elif kind == 'send':
        p.drawLine(12, 19, 12, 5)
        p.drawLine(6, 11, 12, 5)
        p.drawLine(12, 5, 18, 11)
    elif kind == 'stop':
        p.drawRoundedRect(6, 6, 12, 12, 2, 2)
    elif kind == 'mic':
        p.drawRoundedRect(9, 3, 6, 12, 3, 3)
        p.drawArc(6, 7, 12, 12, 180 * 16, 180 * 16)
        p.drawLine(12, 19, 12, 22)
    elif kind == 'settings':
        for y, x in [(6, 9), (12, 15), (18, 8)]:
            p.drawLine(4, y, 20, y)
            p.setBrush(QColor('#1b1922'))
            p.drawEllipse(x - 2, y - 2, 4, 4)
    elif kind == 'file':
        path = QPainterPath()
        path.moveTo(8, 16)
        path.lineTo(16, 8)
        path.cubicTo(21, 3, 25, 9, 20, 14)
        path.lineTo(12, 22)
        path.cubicTo(5, 28, -1, 20, 5, 14)
        path.lineTo(14, 5)
        p.drawPath(path)
    elif kind == 'chat':
        p.drawRoundedRect(4, 4, 16, 13, 3, 3)
        p.drawLine(8, 17, 4, 21)
    else:
        path = QPainterPath()
        path.moveTo(12, 2)
        path.quadTo(13, 10, 22, 12)
        path.quadTo(13, 13, 12, 22)
        path.quadTo(10, 13, 2, 12)
        path.quadTo(10, 10, 12, 2)
        p.drawPath(path)
    p.end()
    pix.setDevicePixelRatio(2)
    return QIcon(pix)

class Mark(QLabel):

    def __init__(self, size=40):
        super().__init__()
        self.setFixedSize(size, size)
        self.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.setPixmap(icon('spark', '#c8b0ff').pixmap(QSize(25, 25)))
        self.setStyleSheet('background:#2a2237;border:1px solid #413052;border-radius:12px;')

class ChatLog(QScrollArea):
    message = pyqtSignal(str)

    def __init__(self):
        super().__init__()
        self._ai_name_lc = 'nexa ai'
        self._cards = []
        self.setWidgetResizable(True)
        self.setFrameShape(QFrame.Shape.NoFrame)
        self.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        self.setStyleSheet('QScrollArea,QScrollArea>QWidget>QWidget{background:transparent;border:0;} QScrollBar:vertical{background:transparent;width:5px;} QScrollBar::handle:vertical{background:#3a3346;border-radius:2px;min-height:30px;} QScrollBar::add-line:vertical,QScrollBar::sub-line:vertical{height:0;}')
        self.canvas = QWidget()
        self.rows = QVBoxLayout(self.canvas)
        self.rows.setContentsMargins(2, 22, 10, 22)
        self.rows.setSpacing(24)
        self.rows.addStretch()
        self.setWidget(self.canvas)
        self.message.connect(self._append)
        self.verticalScrollBar().rangeChanged.connect(lambda lo, hi: self.verticalScrollBar().setValue(hi))

    def append_log(self, value):
        self.message.emit(str(value)[:20000])

    def clear(self):
        for card in self._cards:
            self.rows.removeWidget(card)
            card.deleteLater()
        self._cards.clear()

    def _append(self, value):
        prefix, sep, body = value.partition(':')
        user = prefix.lower() in ('you', 'user')
        ai = prefix.lower() in (self._ai_name_lc, 'nexa', 'nexa ai', 'jarvis')
        name = 'You' if user else 'Nexa AI' if ai else prefix if sep else 'System'
        block = QWidget()
        outer = QHBoxLayout(block)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.setSpacing(12)
        if user:
            outer.addStretch(1)
        else:
            outer.addWidget(Mark(34) if ai else text('·', 20, '#81758f'), 0, Qt.AlignmentFlag.AlignTop)
        card = QFrame()
        card.setMaximumWidth(740)
        card.setStyleSheet('QFrame{background:' + ('#292232' if user else '#191820' if ai else '#15141b') + ';border:1px solid ' + ('#43334f' if user else '#2c2635') + ';border-radius:16px;}')
        inside = QVBoxLayout(card)
        inside.setContentsMargins(20, 16, 20, 19)
        inside.setSpacing(9)
        meta = QHBoxLayout()
        meta.addWidget(text(name, 10, '#c8b0f3' if ai else '#beb1cc', True))
        meta.addSpacing(12)
        meta.addWidget(text(datetime.now().strftime('%H:%M'), 8, '#776c83'))
        meta.addStretch()
        inside.addLayout(meta)
        content = text(body.strip() if sep else value, 11 if user or ai else 9, '#ebe5f1' if user or ai else '#96899f')
        content.setTextFormat(Qt.TextFormat.PlainText)
        content.setWordWrap(True)
        content.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
        inside.addWidget(content)
        outer.addWidget(card, 4)
        if not user:
            outer.addStretch(1)
        self.rows.insertWidget(self.rows.count() - 1, block)
        self._cards.append(block)
        if len(self._cards) > 160:
            old = self._cards.pop(0)
            self.rows.removeWidget(old)
            old.deleteLater()

